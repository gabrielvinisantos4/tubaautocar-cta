export type Status = 'P' | 'A' | 'J';
export type Reg = { s: Status; obs?: string };
export type Registros = Record<string, Record<string, Reg>>;
export type Prof = { id: string; nome: string; esp: string; tel: string; email: string; ativo: boolean };
export type CursoStatus = 'Ativo' | 'Inativo' | 'Em breve';
export type Curso = { id: string; sigla: string; nome: string; desc: string; carga: number; profId: string | null; status: CursoStatus };
export type Turma = { id: string; codigo: string; cursoId: string; profId: string | null; inicio: string; fim: string; hIni: string; hFim: string; dias: number[]; sala: string };
export type AlunoStatus = 'Ativo' | 'Trancado' | 'Concluído';
export type Aluno = { id: string; nome: string; cpf: string; tel: string; email: string; mat: string; turmaId: string; dataMat: string; status: AlunoStatus };
export type TipoAula = 'Teórica' | 'Prática' | 'Avaliação' | 'Workshop';
export type Aula = { id: string; turmaId: string; data: string; hIni: string; hFim: string; conteudo: string; tipo: TipoAula; profId: string | null };
export type DB = { profs: Prof[]; cursos: Curso[]; turmas: Turma[]; alunos: Aluno[]; aulas: Aula[]; registros: Registros };
export type Settings = { min: number; margem: number; jConta: boolean };
export type Stat = { total: number; P: number; A: number; J: number; pct: number | null };
export type Membro = { userId: string; nome: string; usuario: string; papel: 'admin' | 'professor'; ativo: boolean };
export type Route = 'dashboard' | 'chamada' | 'aulas' | 'alunos' | 'turmas' | 'cursos' | 'professores' | 'relatorios' | 'configuracoes';
export type Tone = 'ok' | 'bad' | 'info' | 'warn' | 'accent' | 'muted';
export type ConfirmCfg = { title: string; body: string; confirmLabel: string; danger?: boolean; onConfirm: () => void; cancelLabel?: string };
export type ToastT = { id: number; type: 'success' | 'error' | 'info'; title: string; desc?: string; action?: { label: string; fn: () => void } };
